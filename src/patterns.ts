/**
 * Hand-checked 10×10 nonogram pictures.
 * Names stay in this file. The page does not reveal them.
 * Tests require each picture to be solvable from its clues alone.
 */
export type Pattern = {
  id: string;
  rows: readonly string[];
};

function art(id: string, rows: readonly string[]): Pattern {
  if (rows.length !== 10) {
    throw new Error(`${id} has ${rows.length} rows`);
  }
  for (const row of rows) {
    if (row.length !== 10 || /[^#.]/.test(row)) {
      throw new Error(`${id} has a bad row: ${row}`);
    }
  }
  return { id, rows };
}

function rectangle(
  id: string,
  row0: number,
  col0: number,
  height: number,
  width: number,
): Pattern {
  const rows: string[] = [];
  for (let r = 0; r < 10; r++) {
    let line = '';
    for (let c = 0; c < 10; c++) {
      const inside = r >= row0 && r < row0 + height && c >= col0 && c < col0 + width;
      line += inside ? '#' : '.';
    }
    rows.push(line);
  }
  return art(id, rows);
}

